"""Write c/imbe/imbe_tables.c from mbelib's IMBE 7200x4400 tables (ref/mbelib/imbe7200x4400_const.h, ISC) and the
synthesis tables (Ws from ref/mbelib/mbelib_const.h; cosine, log2, exp2 and the phase offsets computed here, the same
as dmr-vocoder's py/gen_c_tables.py).

Fixed point: the gain G1 and the log2 quantities in Q12, the gain steps in Q24, quantstep x standdev in Q16.

    py py/gen_imbe_tables.py      (after ./fetch_refs.sh)
"""

import math
import os
import re

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
MBELIB = os.path.join(ROOT, "ref", "mbelib")
OUT = os.path.join(ROOT, "c", "imbe", "imbe_tables.c")

# The tables of the hot loops: IMBE_RAM_DATA puts them into RAM on the radio
IN_RAM = {"ImbeCosQ12", "ImbeWsQ15", "ImbeSqrtWsQ15", "ImbeLog2Q12", "ImbeExp2Q15"}


def c_array(path, name):
    """The numbers of `const <type> name[...] = { ... };` in a C header, flattened."""
    text = open(path, encoding="latin-1").read()
    text = re.sub(r"//[^\n]*", "", text)
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    m = re.search(r"\b" + re.escape(name) + r"\s*(\[[^=]*\])\s*=\s*\{(.*?)\};", text, flags=re.S)
    if not m:
        raise SystemExit("%s not found in %s" % (name, path))
    return [float(v) for v in re.findall(r"-?\d+(?:\.\d*)?(?:[eE][-+]?\d+)?", m.group(2))]


def fmt(v):
    return "%d" % v


def array(name, typ, vals, shape=None, comment=""):
    pre = "IMBE_RAM_DATA " if name in IN_RAM else ""
    dims = "".join("[%d]" % d for d in shape) if shape else "[%d]" % len(vals)
    if shape and len(shape) > 1:
        inner = int(np.prod(shape[1:]))
        rows = []
        for r in range(shape[0]):
            row = vals[r * inner:(r + 1) * inner]
            if len(shape) == 3:
                rows.append("    {" + ", ".join("{" + ", ".join(fmt(v) for v in row[i:i + shape[2]]) + "}"
                                              for i in range(0, inner, shape[2])) + "}")
            else:
                rows.append("    {" + ", ".join(fmt(v) for v in row) + "}")
        body = ",\n".join(rows)
    else:
        lines = [", ".join(fmt(v) for v in vals[i:i + 16]) for i in range(0, len(vals), 16)]
        body = ",\n".join("    " + l for l in lines)
    head = ("/* %s */\n" % comment) if comment else ""
    return "%s%sconst %s %s%s = {\n%s\n};\n" % (head, pre, typ, name, dims, body)


def q(v, bits):
    return int(round(v * (1 << bits)))


def main():
    h = os.path.join(MBELIB, "imbe7200x4400_const.h")
    quantstep = c_array(h, "quantstep")
    standdev = c_array(h, "standdev")
    B2 = c_array(h, "B2")
    ba = c_array(h, "ba")
    hoba = c_array(h, "hoba")
    bo = c_array(h, "bo")
    ji = c_array(h, "ImbeJi")
    Ws = c_array(os.path.join(MBELIB, "mbelib_const.h"), "Ws")
    assert len(B2) == 64 and len(ba) == 48 * 5 * 2 and len(hoba) == 48 * 50 and len(bo) == 48 * 79 * 2
    assert len(ji) == 48 * 6 and len(Ws) == 321 and len(standdev) == 9

    out = ['/* The IMBE 7200x4400 tables: generated by py/gen_imbe_tables.py from mbelib\'s (ISC licence, see LICENSE).',
           '   Do not edit. */', '#include "imbe_tables.h"', ""]

    # b0 -> w0 (eq. 46: 4 pi / (b0 + 39.5)) as a phase step (2^32 = 2 pi) and L (eq. 47), as mbelib computes them
    w0q, Ls = [], []
    for b0 in range(208):
        w0 = np.float32(4 * math.pi) / np.float32(b0 + 39.5)
        w0q.append(int(round(2 / (b0 + 39.5) * 2 ** 32)))
        Ls.append(int(0.9254 * int(np.float32(math.pi) / w0 + np.float32(0.25))))
    assert min(Ls) == 9 and max(Ls) == 56
    out.append(array("ImbeW0q", "unsigned int", w0q, comment="w0 of b0 (0..207), 2^32 = 2 pi"))
    out.append(array("ImbeL", "unsigned char", Ls, comment="L of b0"))

    out.append(array("ImbeB2Q12", "int", [q(v, 12) for v in B2], comment="G1 of b2 (log2), Q12"))
    out.append(array("ImbeBaBits", "unsigned char", [int(v) for v in ba[0::2]], (48, 5),
                     comment="bits of b3..b7 (G2..G6) for L - 9"))
    out.append(array("ImbeBaStepQ24", "int", [q(v, 24) for v in ba[1::2]], (48, 5),
                     comment="their step sizes, Q24"))
    out.append(array("ImbeHoba", "unsigned char", [int(v) for v in hoba], (48, 50),
                     comment="bits of b8..b(L+1), the higher order coefficients, for L - 9"))
    out.append(array("ImbeBo", "unsigned char", [int(v) for v in bo], (48, 79, 2),
                     comment="where the 79 bits u0[5..0] u1 .. u6 (imbe_d 6..84) go: (b index, bit) for L - 9"))
    out.append(array("ImbeBlockLen", "unsigned char", [int(v) for v in ji], (48, 6),
                     comment="coefficients of each of the 6 blocks for L - 9"))
    # Cik = quantstep[Bm - 1] x standdev[k - 2] x (bm - 2^(Bm - 1) + 0.5): the product, Q16
    qs = [[q(quantstep[bm - 1] * standdev[k], 16) for k in range(9)] for bm in range(1, 11)]
    out.append(array("ImbeQsSdQ16", "int", [v for r in qs for v in r], (10, 9),
                     comment="quantstep[Bm - 1] x standdev[k - 2], Q16"))

    # synthesis (as dmr-vocoder)
    out.append(array("ImbeCosQ12", "short", [int(round(4096 * math.cos(2 * math.pi * i / 4096))) for i in range(1025)],
                     comment="cos(2 pi i / 4096) x 4096, a quarter of the circle"))
    out.append(array("ImbeWsQ15", "short", [min(32767, int(round(32768 * w))) for w in Ws],
                     comment="the synthesis window Ws x 32768"))
    out.append(array("ImbeSqrtWsQ15", "short", [min(32767, int(round(32768 * math.sqrt(w)))) for w in Ws]))
    disp = np.random.default_rng(12345).uniform(-math.pi, math.pi, 58)
    disp[0] = 0.0
    out.append(array("ImbePhaseDispQ32", "int",
                     [int(np.int32(np.int64(round(v / (2 * math.pi) * 2 ** 32)) & 0xFFFFFFFF)) for v in disp],
                     comment="a fixed pseudo-random phase offset each harmonic, 2^32 = 2 pi"))
    out.append(array("ImbeLog2Q12", "short", [int(round(4096 * math.log2(1 + i / 256))) for i in range(257)],
                     comment="log2(1 + i / 256) x 4096"))
    out.append(array("ImbeExp2Q15", "unsigned short", [min(65535, int(round(32768 * 2 ** (i / 256)))) for i in range(257)],
                     comment="2^(i / 256) x 32768"))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
